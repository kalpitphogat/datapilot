"""Exports a DataPilot conversation as a standalone HTML report with charts embedded."""
import base64
import html
from datetime import datetime

import markdown

STYLE = """
body { font-family: -apple-system, Segoe UI, Roboto, sans-serif; max-width: 860px; margin: 40px auto;
       padding: 0 20px; color: #1f2937; line-height: 1.6; }
header { border-bottom: 3px solid #76B900; margin-bottom: 32px; }
header h1 { margin-bottom: 4px; }
.meta { color: #6b7280; font-size: 14px; margin-bottom: 16px; }
h2.q { margin-top: 40px; font-size: 20px; color: #111827; }
img { max-width: 100%; border: 1px solid #e5e7eb; border-radius: 8px; margin: 12px 0; }
.sources { font-size: 14px; color: #4b5563; }
footer { margin-top: 48px; color: #9ca3af; font-size: 13px; border-top: 1px solid #e5e7eb; padding-top: 12px; }
@media print { body { margin: 0 auto; } }
"""


def build_html_report(dataset_name: str, messages: list[dict]) -> str:
    parts = [
        "<!doctype html><html><head><meta charset='utf-8'>",
        f"<title>DataPilot report - {html.escape(dataset_name)}</title><style>{STYLE}</style></head><body>",
        "<header><h1>📊 DataPilot report</h1>",
        f"<div class='meta'>Dataset: {html.escape(dataset_name)} · Generated {datetime.now():%d %b %Y, %H:%M}</div></header>",
    ]
    for msg in messages:
        if msg["role"] == "user":
            parts.append(f"<h2 class='q'>{html.escape(msg['content'])}</h2>")
            continue
        parts.append(markdown.markdown(msg["content"], extensions=["tables"]))
        for fig in msg.get("figures", []):
            parts.append(f"<img src='data:image/png;base64,{base64.b64encode(fig).decode()}' alt='chart'>")
        if msg.get("sources"):
            links = "".join(
                f"<li><a href='{html.escape(s['url'])}'>{html.escape(s.get('title') or s['url'])}</a></li>"
                for s in msg["sources"]
            )
            parts.append(f"<div class='sources'><strong>Web sources</strong><ul>{links}</ul></div>")
    parts.append("<footer>Generated by DataPilot · NVIDIA Nemotron on Nebius Token Factory. "
                 "Every number comes from executed analysis code.</footer></body></html>")
    return "".join(parts)
